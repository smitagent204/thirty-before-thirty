/**
 * Узкая перепроверка после апелляции. Первый проход оставил часть замечаний
 * без изменений — спрашиваем только про них и только «подтверждает ли кадр
 * довод», чтобы честное пояснение не упиралось в минимальный процент.
 */
export function buildAppealRecheckPrompt(
  task: Task,
  claims: AppealClaim[],
  note: string,
): string {
  return [
    'Ты — доброжелательный модератор фотоотчётов в личном квесте «30 до 30». Человек оспорил снижение оценки и подробно объяснил, что было на фото. Первый пересмотр оставил эти замечания без изменений. Перечитай пояснение и посмотри на фото ещё раз: подтверждает ли кадр слова человека хотя бы частично?',
    '',
    `ЗАДАНИЕ: ${task.title}`,
    `ОПИСАНИЕ: ${task.description}`,
    `ЧТО ЧЕЛОВЕКУ СКАЗАЛИ СНЯТЬ: ${task.photoHint}`,
    '',
    'ОСПАРИВАЕМЫЕ ЗАМЕЧАНИЯ:',
    claims
      .map((claim) => {
        const requirement = task.rubric.required.find((item) => item.id === claim.id);
        return `- id: ${claim.id} · ${requirement?.label ?? claim.label}`;
      })
      .join('\n'),
    '',
    'ПОЯСНЕНИЕ ЧЕЛОВЕКА:',
    `«${note}»`,
    '',
    'Как отвечать:',
    '1. Для каждого замечания верни state:',
    '   - «ok» — кадр подтверждает довод, даже если деталь видна не сразу или её часть скрыта ракурсом;',
    '   - «partial» — довод правдоподобен, но кадр подтверждает только часть;',
    '   - «no» — кадр прямо противоречит доводу или в нём нет ничего похожего.',
    '2. Человек был на месте и знает контекст. Его пояснение — дополнительная информация, которой может не быть в кадре. Если кадр не противоречит сказанному, выбирай ok или partial, а не no.',
    '3. Оценивай пункты независимо, не добавляй новых и не усиливай прежние.',
    '',
    'ФОРМАТ ОТВЕТА — строго JSON:',
    '{"checks": [{"id": "<id из списка>", "state": "ok" | "partial" | "no"}]}',
  ].join('\n');
}

