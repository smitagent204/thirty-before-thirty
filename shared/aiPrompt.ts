const OUTPUT_FORMAT = `ФОРМАТ ОТВЕТА — строго JSON:
{"score": <целое 0..100>, "verdict": "pass" | "fail", "reason": "<1-2 предложения без процентов>", "confidence": <0..1>, "deductions": [{"label": "<чего не хватило, читается после «за»>", "percent": <целое>}]}`;

export interface Deduction {
  label: string;
  percent: number;
}

export interface PreviousAttempt {
  score: number;
  reason: string;
}

function bulletList(items: string[]): string {
  return items.map((item) => `- ${item}`).join('\n');
}

export function buildVerdictPrompt(task: Task, previous?: PreviousAttempt | null): string {
  return [
    VERDICT_SYSTEM_PROMPT,
    '',
    `ЗАДАНИЕ: ${task.title}`,
    `СУТЬ: ${task.description}`,
    `ЧТО ЧЕЛОВЕКУ СКАЗАЛИ СНЯТЬ: ${task.photoHint}`,
    ...(previous
      ? [
          '',
          'ПРЕДЫДУЩАЯ ПОПЫТКА (это повторная загрузка того же задания):',
          `Оценка: ${previous.score}%. Комментарий: ${previous.reason}`,
          'Проверь, исправлены ли замечания из предыдущего комментария. Если да — отметь это и не снижай за них снова. Если нет — мягко напомни, что ещё можно поправить.',
        ]
      : []),
    '',
    'ОБЯЗАТЕЛЬНАЯ ОСНОВА (без неё задание не выполнено):',
    bulletList(task.rubric.base),
    '',
    'ХОРОШО, ЕСЛИ НА ФОТО (необязательно, повышает оценку):',
    bulletList(task.rubric.good),
    '',
    'БОНУС (необязательно, выводит оценку на 90–100):',
    bulletList(task.rubric.bonus),
    '',
    'СНИЖАЕТ ОЦЕНКУ (только эти пункты реально уменьшают балл):',
    bulletList(task.rubric.penalties),
    '',
    SCORING_RULES,
    '',
    OUTPUT_FORMAT,
  ].join('\n');
}

