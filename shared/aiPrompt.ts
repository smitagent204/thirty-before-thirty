    'ФОРМАТ ОТВЕТА — строго JSON:',
    '{"checks": [{"id": "<id из списка>", "reduce": <целое от 0 до текущего штрафа>}], "reason": "<3-6 предложений: что видно, почему замечание осталось или снято и что нужно, чтобы его снять>"}',
